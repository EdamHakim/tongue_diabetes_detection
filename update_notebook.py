    "        history['val_acc'].append(v_acc)\n",
    "        history['val_auc'].append(v_auc)\n",
    "        \n",
    "        scheduler.step(v_loss)\n",
    "        \n",
    "        print(f\"Epoch {epoch+1}/{epochs} | \"\n",
