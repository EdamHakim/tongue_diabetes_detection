            "    \n",
            "    heatmap = np.zeros((output_height, output_width))\n",
            "    \n",
            "    for h in range(output_height):\n",
            "        for w in range(output_width):\n",
            "            h_start = h * stride\n",
            "            w_start = w * stride\n",
            "            h_end = min(height, h_start + patch_size)\n",
